import { and, asc, count, eq, ilike, or, sql } from "drizzle-orm";

import { db } from "@/src/db/client";
import { items, vItemStock } from "@/src/db/schema";
import { AppError } from "@/src/lib/errors";
import {
  requireItemCreateFields,
  type ItemCreateInput,
  type ItemListInput,
  type ItemUpdateInput,
} from "@/src/lib/schemas/items";
import { paginationOffset } from "@/src/lib/schemas/common";

const itemResponseColumns = {
  id: items.id,
  itemCode: items.itemCode,
  barcode: items.barcode,
  itemName: items.itemName,
  categoryMajor: items.categoryMajor,
  categoryMinor: items.categoryMinor,
  unitSpec: items.unitSpec,
  unitName: items.unitName,
  packQty: items.packQty,
  packUnit: items.packUnit,
  purchasePrice: items.purchasePrice,
  supplyPrice: items.supplyPrice,
  minStockQty: items.minStockQty,
  remarks: items.remarks,
  isActive: items.isActive,
  onHandQty: vItemStock.onHandQty,
  allocatedQty: vItemStock.allocatedQty,
  availableQty: vItemStock.availableQty,
  isBelowMinStock: sql<boolean>`case when ${items.minStockQty} is not null and ${vItemStock.onHandQty} < ${items.minStockQty} then true else false end`,
};

function hasItemCodeUniqueViolation(failure: unknown) {
  if (!failure || typeof failure !== "object") {
    return false;
  }

  const errorLike = failure as { code?: unknown; cause?: { code?: unknown } };
  return errorLike.code === "23505" || errorLike.cause?.code === "23505";
}

export async function listItems(values: ItemListInput) {
  const conditions = [
    ...(values.itemKeyword ? [ilike(items.itemName, `%${values.itemKeyword}%`)] : []),
    ...(values.specKeyword
      ? [
          or(
            ilike(items.unitSpec, `%${values.specKeyword}%`),
            ilike(items.unitName, `%${values.specKeyword}%`),
            ilike(items.packUnit, `%${values.specKeyword}%`),
          ),
        ]
      : []),
  ];
  const where = conditions.length > 0 ? and(...conditions) : undefined;

  const [data, totalResult] = await Promise.all([
    db
      .select(itemResponseColumns)
      .from(items)
      .innerJoin(vItemStock, eq(vItemStock.itemId, items.id))
      .where(where)
      .orderBy(asc(items.itemCode))
      .limit(values.size)
      .offset(paginationOffset(values)),
    db.select({ totalElements: count() }).from(items).where(where),
  ]);

  return { data, totalElements: totalResult[0]?.totalElements ?? 0 };
}

export async function getItem(itemId: number) {
  const [item] = await db
    .select(itemResponseColumns)
    .from(items)
    .innerJoin(vItemStock, eq(vItemStock.itemId, items.id))
    .where(eq(items.id, itemId))
    .limit(1);

  if (!item) {
    throw new AppError("NOT_FOUND");
  }

  return item;
}

export async function listSpecParseFailedItems(values: ItemListInput) {
  const [data, totalResult] = await Promise.all([
    db
      .select(itemResponseColumns)
      .from(items)
      .innerJoin(vItemStock, eq(vItemStock.itemId, items.id))
      .where(eq(items.isSpecParseFailed, true))
      .orderBy(asc(items.itemCode))
      .limit(values.size)
      .offset(paginationOffset(values)),
    db
      .select({ totalElements: count() })
      .from(items)
      .where(eq(items.isSpecParseFailed, true)),
  ]);

  return { data, totalElements: totalResult[0]?.totalElements ?? 0 };
}

export async function createItem(values: ItemCreateInput) {
  requireItemCreateFields(values);

  // BR-ITM-003: unique conflicts are retried instead of caching the current maximum.
  for (let retryNumber = 0; retryNumber < 3; retryNumber += 1) {
    try {
      return await db.transaction(async (transaction) => {
        const [maximum] = await transaction
          .select({
            itemCode: sql<string | null>`max(case when ${items.itemCode} ~ '^[0-9]+$' then ${items.itemCode}::bigint end)`,
          })
          .from(items);
        const nextItemCode = (BigInt(String(maximum?.itemCode ?? "0")) + BigInt(1)).toString();

        const [createdItem] = await transaction
          .insert(items)
          .values({
            // BR-ITM-002: itemCode is generated by the server, not trusted from the request.
            itemCode: nextItemCode,
            itemName: values.itemName,
            barcode: values.barcode,
            categoryMajor: values.categoryMajor,
            categoryMinor: values.categoryMinor,
            unitSpec: values.unitSpec,
            unitName: values.unitName,
            packQty: values.packQty,
            packUnit: values.packUnit,
            purchasePrice: values.purchasePrice,
            supplyPrice: values.supplyPrice,
            minStockQty: values.minStockQty,
            remarks: values.remarks,
          })
          .returning({ id: items.id });

        if (!createdItem) {
          throw new AppError("CONCURRENCY_CONFLICT");
        }

        return createdItem.id;
      });
    } catch (failure) {
      if (!hasItemCodeUniqueViolation(failure)) {
        throw failure;
      }

      if (retryNumber === 2) {
        throw new AppError("CONCURRENCY_CONFLICT");
      }
    }
  }

  throw new AppError("CONCURRENCY_CONFLICT");
}

export async function updateItem(itemId: number, values: ItemUpdateInput) {
  if (Object.prototype.hasOwnProperty.call(values, "itemCode")) {
    // BR-ITM-004: no application caller may update an itemCode.
    throw new AppError("ITEM_CODE_IMMUTABLE");
  }

  const { itemCode: _ignoredItemCode, ...updatableValues } = values;

  const [updatedItem] = await db
    .update(items)
    .set({ ...updatableValues, updatedAt: new Date() })
    .where(eq(items.id, itemId))
    .returning({ id: items.id });

  if (!updatedItem) {
    throw new AppError("NOT_FOUND");
  }
}

export async function deactivateItem(itemId: number) {
  const [deactivatedItem] = await db
    .update(items)
    .set({ isActive: false, updatedAt: new Date() })
    .where(eq(items.id, itemId))
    .returning({ id: items.id });

  if (!deactivatedItem) {
    throw new AppError("NOT_FOUND");
  }
}
